/**
 * CampusMitra Safe Demo-Data Cleanup Script
 *
 * SAFETY GUARANTEES:
 * 1. Safe by default: Defaults to --dry-run mode unless --execute is explicitly specified.
 * 2. Backs up database state prior to any destructive operation.
 * 3. Never drops collections or resets the database.
 * 4. Preserves authentic student accounts (e.g. borseajay266@mitwpu.edu.in, 1272250478@mitwpu.edu.in).
 * 5. Uses defensible, explicit test-pattern criteria only.
 * 6. Dependency-aware cascade: Cleans up child records cleanly across all collections.
 *
 * Usage:
 *   node src/scripts/cleanupDemoData.js            # Dry run report (safe, read-only)
 *   node src/scripts/cleanupDemoData.js --dry-run  # Explicit dry run
 *   node src/scripts/cleanupDemoData.js --backup   # Create local backup only
 *   node src/scripts/cleanupDemoData.js --execute  # Execute targeted cleanup (requires confirmation)
 */
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const mongoose = require('mongoose');

const MONGODB_URI = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/campusmitra';

// Defensible test patterns:
// 1. Explicit 13-digit timestamp test accounts generated by automated test suites: e.g. *.1791...
const TIMESTAMP_REGEX = /[\._]\d{12,14}@mitwpu\.edu\.in$/i;

// 2. Known seed test accounts defined in src/scripts/seed.js:
const SEED_TEST_EMAILS = [
  'priya.test@mitwpu.edu.in',
  'rahul.test@mitwpu.edu.in',
  'sneha.test@mitwpu.edu.in',
  'admin.moderator@mitwpu.edu.in',
];

// 3. Test suites static accounts that are strictly test runner fixtures:
const SUITE_FIXTURE_EMAILS = [
  'vibe.alice@mitwpu.edu.in',
  'vibe.bob@mitwpu.edu.in',
  'vibe.charlie@mitwpu.edu.in',
];

// Whitelist of verified authentic accounts and accounts that MUST NEVER be deleted:
const PRESERVED_ACCOUNTS = [
  'borseajay266@mitwpu.edu.in', // Project owner / authentic student
  '1272250478@mitwpu.edu.in',  // Authentic registered student
  'johnn@mitwpu.edu.in',
  'aloha@mitwpu.edu.in',
  'circle.alice@mitwpu.edu.in',
  'circle.bob@mitwpu.edu.in',
  'circle.charlie@mitwpu.edu.in',
  'pulse.alice@mitwpu.edu.in',
  'pulse.bob@mitwpu.edu.in',
  'pulse.charlie@mitwpu.edu.in',
];

const isTestAccount = (user) => {
  const email = (user.email || '').toLowerCase().trim();

  // If in preserved whitelist, NEVER delete
  if (PRESERVED_ACCOUNTS.includes(email)) {
    return false;
  }

  // Check timestamp test runner pattern
  if (TIMESTAMP_REGEX.test(email)) {
    return true;
  }

  // Check known seed test emails
  if (SEED_TEST_EMAILS.includes(email)) {
    return true;
  }

  // Check test suite fixture emails
  if (SUITE_FIXTURE_EMAILS.includes(email)) {
    return true;
  }

  // Check explicit test marker in name
  if (
    (user.lastName && user.lastName.includes('[TEST]')) ||
    (user.firstName && user.firstName.includes('[TEST]'))
  ) {
    return true;
  }

  return false;
};

async function createBackup(db) {
  const backupDir = path.join(__dirname, '../../backups', `backup-${Date.now()}`);
  fs.mkdirSync(backupDir, { recursive: true });

  const collections = await db.listCollections().toArray();
  const summary = {};

  for (const col of collections) {
    const docs = await db.collection(col.name).find({}).toArray();
    fs.writeFileSync(
      path.join(backupDir, `${col.name}.json`),
      JSON.stringify(docs, null, 2),
      'utf8'
    );
    summary[col.name] = docs.length;
  }

  console.log(`\n💾 Database backup successfully saved to:\n   ${backupDir}`);
  return { backupDir, summary };
}

async function run() {
  const args = process.argv.slice(2);
  const isExecute = args.includes('--execute');
  const backupOnly = args.includes('--backup');

  console.log('====================================================');
  console.log('🧹 CAMPUSMITRA SAFE DEMO-DATA CLEANUP AUDITOR');
  console.log('====================================================');
  console.log(`Mode: ${isExecute ? '⚠️ LIVE EXECUTION' : '🛡️ DRY-RUN ONLY (Safe)'}`);
  console.log(`Database URI: ${MONGODB_URI.replace(/:([^:@]+)@/, ':****@')}\n`);

  await mongoose.connect(MONGODB_URI);
  const db = mongoose.connection.db;

  if (backupOnly) {
    await createBackup(db);
    process.exit(0);
  }

  // 1. Identify test users
  const allUsers = await db.collection('users').find({}).toArray();
  const testUsers = allUsers.filter(isTestAccount);
  const preservedUsers = allUsers.filter((u) => !isTestAccount(u));

  const testUserIds = testUsers.map((u) => u._id);
  const testUserIdStrs = testUserIds.map((id) => id.toString());

  console.log(`Found ${allUsers.length} total user records in MongoDB.`);
  console.log(` - Preserved Authentic / Real Users: ${preservedUsers.length}`);
  console.log(` - Identified Demo / Test Artifact Users: ${testUsers.length}\n`);

  console.log('🛡️ Preserved Authentic Student Accounts:');
  preservedUsers.forEach((u, i) => {
    console.log(`   ${i + 1}. ${u.email} (${u.firstName} ${u.lastName})`);
  });
  console.log('');

  // 2. Identify dependent documents across all collections
  const profilesCount = await db.collection('profiles').countDocuments({
    user: { $in: testUserIds },
  });

  const connectionsCount = await db.collection('connections').countDocuments({
    $or: [{ user1: { $in: testUserIds } }, { user2: { $in: testUserIds } }],
  });

  const notificationsCount = await db.collection('notifications').countDocuments({
    $or: [{ recipient: { $in: testUserIds } }, { sender: { $in: testUserIds } }],
  });

  const messagesCount = await db.collection('messages').countDocuments({
    sender: { $in: testUserIds },
  });

  // Conversations where all participants are test users
  const conversationsAll = await db.collection('conversations').find({}).toArray();
  const conversationsToDelete = conversationsAll.filter((conv) => {
    if (!conv.participants || conv.participants.length === 0) return true;
    return conv.participants.every((p) => testUserIdStrs.includes(p.toString()));
  });

  const availabilitiesCount = await db.collection('availabilities').countDocuments({
    user: { $in: testUserIds },
  });

  const verificationsCount = await db.collection('verifications').countDocuments({
    user: { $in: testUserIds },
  });

  const verificationTokensCount = await db.collection('verificationtokens').countDocuments({
    user: { $in: testUserIds },
  });

  const auditLogsCount = await db.collection('auditlogs').countDocuments({
    $or: [{ admin: { $in: testUserIds } }, { targetUser: { $in: testUserIds } }],
  });

  console.log('====================================================');
  console.log('📊 DRY-RUN CLEANUP REPORT (Records to be removed)');
  console.log('====================================================');
  console.log(` 1. users:               ${testUsers.length} test records`);
  console.log(` 2. profiles:            ${profilesCount} associated test profiles`);
  console.log(` 3. connections:         ${connectionsCount} test swiped connections`);
  console.log(` 4. conversations:       ${conversationsToDelete.length} test conversations`);
  console.log(` 5. messages:            ${messagesCount} test messages`);
  console.log(` 6. notifications:       ${notificationsCount} test notifications`);
  console.log(` 7. availabilities:      ${availabilitiesCount} test radar availabilities`);
  console.log(` 8. verifications:       ${verificationsCount} test ID verifications`);
  console.log(` 9. verificationtokens:  ${verificationTokensCount} test tokens`);
  console.log(`10. auditlogs:           ${auditLogsCount} test audit logs`);
  console.log('----------------------------------------------------');
  console.log(`Total records identified for safe removal: ${
    testUsers.length +
    profilesCount +
    connectionsCount +
    conversationsToDelete.length +
    messagesCount +
    notificationsCount +
    availabilitiesCount +
    verificationsCount +
    verificationTokensCount +
    auditLogsCount
  }`);
  console.log('====================================================\n');

  if (!isExecute) {
    console.log('🔒 DRY-RUN COMPLETE: No changes were made to the database.');
    console.log('💡 To back up database before cleanup, run:');
    console.log('   node src/scripts/cleanupDemoData.js --backup');
    console.log('💡 To execute cleanup after explicit approval, run:');
    console.log('   node src/scripts/cleanupDemoData.js --execute\n');
    process.exit(0);
  }

  // Live Execution (Only if explicitly requested)
  console.log('Creating safety backup before executing deletion...');
  await createBackup(db);

  console.log('\nExecuting targeted cleanup...');
  await db.collection('profiles').deleteMany({ user: { $in: testUserIds } });
  await db.collection('connections').deleteMany({
    $or: [{ user1: { $in: testUserIds } }, { user2: { $in: testUserIds } }],
  });
  await db.collection('notifications').deleteMany({
    $or: [{ recipient: { $in: testUserIds } }, { sender: { $in: testUserIds } }],
  });
  await db.collection('messages').deleteMany({ sender: { $in: testUserIds } });

  const convIdsToDelete = conversationsToDelete.map((c) => c._id);
  if (convIdsToDelete.length > 0) {
    await db.collection('conversations').deleteMany({ _id: { $in: convIdsToDelete } });
  }

  await db.collection('availabilities').deleteMany({ user: { $in: testUserIds } });
  await db.collection('verifications').deleteMany({ user: { $in: testUserIds } });
  await db.collection('verificationtokens').deleteMany({ user: { $in: testUserIds } });
  await db.collection('auditlogs').deleteMany({
    $or: [{ admin: { $in: testUserIds } }, { targetUser: { $in: testUserIds } }],
  });

  await db.collection('users').deleteMany({ _id: { $in: testUserIds } });

  console.log('✅ Targeted cleanup finished successfully.');
  console.log(`Preserved ${preservedUsers.length} authentic student accounts.\n`);
  process.exit(0);
}

run().catch((err) => {
  console.error('❌ Error during cleanup script:', err);
  process.exit(1);
});
